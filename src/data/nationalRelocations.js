export function computeNationalSummary(records) {
  const activeStatuses = new Set(['Planned', 'In Progress', 'Delayed'])
  const active = records.filter((r) => activeStatuses.has(r.status))
  const totalPeople = records.reduce((sum, r) => sum + r.peopleCount, 0)
  const states = new Set(records.map((r) => r.state))
  const temporary = records.filter((r) => r.relocationType !== 'Permanent').length
  const permanent = records.filter((r) => r.relocationType === 'Permanent').length

  return {
    activeCount: active.length,
    totalPeople,
    stateCount: states.size,
    temporaryCount: temporary,
    permanentCount: permanent,
  }
}
